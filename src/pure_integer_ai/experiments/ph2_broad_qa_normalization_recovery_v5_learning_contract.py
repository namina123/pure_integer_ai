def normalization_recovery_v5_rule_class(
        fragment_kind: str,
        *,
        equal_length: int,
        ) -> str:
    """把 fragment kind 与长度事实映射到稳定 learner 规则分桶。"""
    if fragment_kind in {"CONTEXT_HUNK", "EDIT_CORE"}:
        return fragment_kind
    if fragment_kind == "WHOLE_INPUT" and equal_length == 1:
        return "WHOLE_INPUT_EQUAL_LENGTH"
    if fragment_kind == "WHOLE_INPUT" and equal_length == 0:
        return "WHOLE_INPUT_VARIABLE_LENGTH"
    raise ValueError("recovery-v5 fragment kind/equal_length 非法")


